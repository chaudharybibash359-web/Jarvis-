package com.example.data.remote

import android.util.Log
import com.example.BuildConfig
import com.example.domain.model.Personality
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

class GeminiClient {

    private val client = OkHttpClient.Builder()
        .connectTimeout(60, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .writeTimeout(60, TimeUnit.SECONDS)
        .build()

    private val jsonMediaType = "application/json; charset=utf-8".toMediaType()

    suspend fun generateResponse(
        userQuery: String,
        conversationHistory: List<Pair<String, Boolean>>, // text to isUser
        memories: List<String>,
        personality: Personality,
        userHonorific: String,
        customApiKey: String,
        selectedModel: String = "gemini-3.5-flash"
    ): Result<String> = withContext(Dispatchers.IO) {
        val apiKey = customApiKey.ifBlank {
            try {
                BuildConfig.GEMINI_API_KEY
            } catch (e: Exception) {
                ""
            }
        }.trim()

        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext Result.failure(
                IllegalStateException("NO_API_KEY")
            )
        }

        try {
            val systemPrompt = buildSystemPrompt(personality, userHonorific, memories)

            // Construct JSON request
            val rootJson = JSONObject()

            // System Instruction
            val systemObj = JSONObject()
            val systemParts = JSONArray()
            systemParts.put(JSONObject().put("text", systemPrompt))
            systemObj.put("parts", systemParts)
            rootJson.put("systemInstruction", systemObj)

            // Contents array
            val contentsArray = JSONArray()

            // Add previous recent turns (up to 8 turns for context window efficiency)
            val recentTurns = conversationHistory.takeLast(8)
            for (turn in recentTurns) {
                val contentObj = JSONObject()
                contentObj.put("role", if (turn.second) "user" else "model")
                val parts = JSONArray()
                parts.put(JSONObject().put("text", turn.first))
                contentObj.put("parts", parts)
                contentsArray.put(contentObj)
            }

            // Current user turn
            val currentTurn = JSONObject()
            currentTurn.put("role", "user")
            val currentParts = JSONArray()
            currentParts.put(JSONObject().put("text", userQuery))
            currentTurn.put("parts", currentParts)
            contentsArray.put(currentTurn)

            rootJson.put("contents", contentsArray)

            // Generation config
            val genConfig = JSONObject()
            genConfig.put("temperature", 0.7)
            genConfig.put("maxOutputTokens", 600)
            rootJson.put("generationConfig", genConfig)

            val url = "https://generativelanguage.googleapis.com/v1beta/models/$selectedModel:generateContent?key=$apiKey"

            val body = rootJson.toString().toRequestBody(jsonMediaType)
            val request = Request.Builder()
                .url(url)
                .post(body)
                .build()

            val response = client.newCall(request).execute()
            val responseBody = response.body?.string().orEmpty()

            if (!response.isSuccessful) {
                Log.e("GeminiClient", "HTTP error ${response.code}: $responseBody")
                val errorMessage = parseErrorMessage(responseBody, response.code)
                return@withContext Result.failure(Exception(errorMessage))
            }

            val jsonResponse = JSONObject(responseBody)
            val candidates = jsonResponse.optJSONArray("candidates")
            if (candidates != null && candidates.length() > 0) {
                val firstCandidate = candidates.getJSONObject(0)
                val content = firstCandidate.optJSONObject("content")
                val parts = content?.optJSONArray("parts")
                if (parts != null && parts.length() > 0) {
                    val text = parts.getJSONObject(0).optString("text", "")
                    if (text.isNotBlank()) {
                        return@withContext Result.success(text)
                    }
                }
            }

            Result.failure(Exception("No response text generated by AI model."))
        } catch (e: Exception) {
            Log.e("GeminiClient", "Network failure", e)
            Result.failure(e)
        }
    }

    private fun buildSystemPrompt(
        personality: Personality,
        userHonorific: String,
        memories: List<String>
    ): String {
        val memoryBlock = if (memories.isNotEmpty()) {
            "\nStored User Facts & Context:\n" + memories.joinToString("\n") { "- $it" } + "\n"
        } else ""

        return """
${personality.systemPromptDirective}
Current user title / honorific: "$userHonorific". Address the user appropriately (e.g. "$userHonorific").
$memoryBlock
Available Supported Device Actions:
If the user asks to perform an action on their phone, append an exact action tag at the END of your conversational reply:
- Open application: [ACTION: OPEN_APP: app_name]
- Search web: [ACTION: SEARCH: query]
- Launch maps: [ACTION: MAPS: location]
- Turn flashlight on/off: [ACTION: FLASHLIGHT: ON] or [ACTION: FLASHLIGHT: OFF]
- Set alarm: [ACTION: ALARM: HH:MM: label]
- Call someone: [ACTION: CALL: name_or_number]
- Send message: [ACTION: MESSAGE: recipient: message_text]
- Remember information: [ACTION: REMEMBER: fact_or_preference]

CRITICAL VOICE INSTRUCTIONS:
- You are speaking aloud through text-to-speech. Keep responses concise, clear, and direct (1 to 3 sentences usually).
- Avoid Markdown formatting like asterisks, code blocks, or bullet lists in speech text, as screen readers speak them awkwardly.
- Be polite, intelligent, and authentic to your personality.
        """.trimIndent()
    }

    private fun parseErrorMessage(errorBody: String, code: Int): String {
        return try {
            val json = JSONObject(errorBody)
            val error = json.optJSONObject("error")
            val message = error?.optString("message", "") ?: ""
            when {
                code == 400 && message.contains("API_KEY_INVALID") -> "Invalid API Key. Please verify your Gemini API key in Settings."
                code == 429 || message.contains("RESOURCE_EXHAUSTED") -> "Rate limit reached. Please wait a few moments before trying again."
                code == 403 -> "Permission denied for this model or API key."
                message.isNotBlank() -> message
                else -> "Server returned error code $code"
            }
        } catch (e: Exception) {
            "API request failed with status $code"
        }
    }
}
